#pragma once
#include "permutation.h"
#include <array>
#include <cstdint>
#include <functional>
#include <set>
#include <vector>

// ── Small permutation-group toolkit ───────────────────────────────────────────
//
// Everything here works on the same Permutation<N> type used by the moves, so a
// group is just a list of generators.  The only non-trivial routine is an exact
// Schreier–Sims order computation; it is used to check, for example, that
// |<R,U>| = 73,483,200 and that the half-turn subgroup used in the God's Number
// proof has order 19,508,428,800.

namespace group {

template<int N>
using Perm = Permutation<N>;

template<int N>
bool is_identity(const Perm<N>& g) {
    for (int i = 0; i < N; ++i) if (g.p[i] != i) return false;
    return true;
}

// Remove duplicates and the identity, preserving nothing about order.
template<int N>
std::vector<Perm<N>> clean(std::vector<Perm<N>> gens) {
    std::set<std::array<int, N>> seen;
    std::vector<Perm<N>> out;
    for (auto& g : gens) {
        if (is_identity(g)) continue;
        if (seen.insert(g.p).second) out.push_back(g);
    }
    return out;
}

// Orbit of `start` under the group generated by `gens`.
template<int N>
std::vector<int> orbit_of(int start, const std::vector<Perm<N>>& gens) {
    std::vector<int> orb{start};
    std::array<bool, N> seen{};
    seen[start] = true;
    for (std::size_t i = 0; i < orb.size(); ++i) {
        int x = orb[i];
        for (auto& g : gens) {
            int y = g.p[x];
            if (!seen[y]) { seen[y] = true; orb.push_back(y); }
        }
    }
    return orb;
}

// Orbit decomposition of all N points.  The number of orbits is the dimension
// of the fixed subspace of the natural permutation representation.
template<int N>
std::vector<std::vector<int>> orbits(const std::vector<Perm<N>>& gens) {
    std::array<bool, N> seen{};
    std::vector<std::vector<int>> out;
    for (int i = 0; i < N; ++i) {
        if (seen[i]) continue;
        auto orb = orbit_of(i, gens);
        for (int x : orb) seen[x] = true;
        out.push_back(std::move(orb));
    }
    return out;
}

namespace detail {

// Recursive orbit-stabiliser with Schreier generators.  `fixed` lists the base
// points already fixed by every generator.
template<int N>
std::uint64_t order_rec(std::vector<Perm<N>> gens, std::vector<int> fixed) {
    gens = clean(std::move(gens));
    if (gens.empty()) return 1;

    // Choose a base point that some generator still moves.
    int b = -1;
    for (int i = 0; i < N && b < 0; ++i) {
        bool already = false;
        for (int f : fixed) if (f == i) { already = true; break; }
        if (already) continue;
        for (auto& g : gens) if (g.p[i] != i) { b = i; break; }
    }
    if (b < 0) return 1;

    // Orbit of b and a transversal t_x with t_x(b) = x.
    std::vector<int> orb{b};
    std::array<bool, N> seen{};
    seen[b] = true;
    std::vector<Perm<N>> trans{ Perm<N>::identity() };
    for (std::size_t i = 0; i < orb.size(); ++i) {
        int x = orb[i];
        for (auto& g : gens) {
            int y = g.p[x];
            if (!seen[y]) {
                seen[y] = true;
                orb.push_back(y);
                // t_y = g ∘ t_x
                trans.push_back(g.compose(trans[i]));
            }
        }
    }

    // Schreier generators of the stabiliser of b (and all earlier points).
    std::vector<Perm<N>> sgens;
    for (std::size_t i = 0; i < orb.size(); ++i) {
        for (auto& g : gens) {
            int y = g.p[orb[i]];
            // Find the transversal index for y.
            std::size_t j = 0;
            while (j < orb.size() && orb[j] != y) ++j;
            // s = t_y^{-1} ∘ g ∘ t_x  fixes b.
            sgens.push_back(trans[j].inverse().compose(g).compose(trans[i]));
        }
    }

    fixed.push_back(b);
    return (std::uint64_t)orb.size() * order_rec<N>(std::move(sgens), std::move(fixed));
}

} // namespace detail

// Exact order of the group generated by `gens`.  Only safe while the order fits
// in 64 bits; all groups used in the demos do.  (|G| for the full 3x3 is
// 4.3e19, so that one is computed combinatorially instead.)
template<int N>
std::uint64_t order(std::vector<Perm<N>> gens) {
    return detail::order_rec<N>(std::move(gens), {});
}

} // namespace group
